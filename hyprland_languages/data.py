def get_flag_emoji(country_code: str) -> str:
    """Converts a 2-letter ISO country code to an emoji flag."""
    if not country_code or len(country_code) != 2:
        return "🌐"
    try:
        cc = country_code.upper()
        return "".join(chr(127397 + ord(c)) for c in cc)
    except Exception:
        return "🌐"

